export const isLocale = (v: unknown): v is Locale => v === "lv" || v === "en";

const MONTHS_EN = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

/** YYYY-MM-DD -> LV "27.11.2026.", EN "27 Nov 2026" (LV matches the chart's date style) */
export function formatDate(iso: string, locale: Locale): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso);
  if (!m) return iso;
  const [, y, mo, d] = m;
  return locale === "lv" ? `${d}.${mo}.${y}.` : `${d} ${MONTHS_EN[Number(mo) - 1] ?? mo} ${y}`;
}

/** LV uses a decimal comma, EN a decimal point */
export function formatNumber(n: number, locale: Locale, maxDigits = 2): string {
  return new Intl.NumberFormat(locale === "lv" ? "lv-LV" : "en-GB", { maximumFractionDigits: maxDigits }).format(n);
}

/** English: 1 day / 2 days */
const enPl = (n: number, one: string, many: string) => (n === 1 ? one : many);
/** Latvian: numbers ending in 1 (but not 11) take the singular: 1, 21, 101 diena; 2, 11, 12 dienas */
const lvPl = (n: number, one: string, many: string) => (Math.abs(n) % 10 === 1 && Math.abs(n) % 100 !== 11 ? one : many);

/** Values carried by a parser note (lib/parse.ts) */
type NoteP = Record<string, string | number | boolean>;
const fmtN = (v: unknown, locale: Locale) => (typeof v === "number" ? formatNumber(v, locale) : String(v ?? ""));

